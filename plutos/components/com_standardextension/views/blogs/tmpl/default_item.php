defined('_JEXEC') or die;

// Create a shortcut for params.
$params = &$this->item->params;

$images = json_decode($this->item->images);

$canEdit = $this->item->params->get('access-edit');
$info = $this->item->params->get('info_block_position', 0);

// Check if associations are implemented. If they are, define the parameter.
$assocParam = (JLanguageAssociations::isEnabled() && $params->get('show_associations'));

$currentDate = JFactory::getDate()->format('Y-m-d H:i:s');
$isExpired = $this->item->publish_down < $currentDate && $this->item->publish_down !== JFactory::getDbo()->getNullDate();
$isNotPublishedYet = $this->item->publish_up > $currentDate;
$isUnpublished = $this->item->state == 0 || $isNotPublishedYet || $isExpired;
?>
<div class="item d-flex flex-fill rounded border border-color-item mb-4 column-<?php echo $this->rowcount; ?>"> <?php // box-shadow ?>
    <?php if ($isUnpublished) : ?>
        <div class="system-unpublished">
        <?php endif; ?>
        <div class="row">
            <?php
            $class_item_image = "post d-flex col-12 col-sm-7 col-md-6 col-lg-7";
            $class_item_text = "post d-flex col-12 col-sm-5 col-md-6 col-lg-5";
            $cItemText = "item-text flex-fill pr-sm-3";
            ?>
            <?php if (isset($images->image_medium) && !empty($images->image_medium)) : ?>
                <?php $imgfloat = empty($images->float_intro) ? $params->get('float_intro') : $images->float_intro; ?>
                <div class="<?php echo $class_item_image; ?> pull-<?php echo htmlspecialchars($imgfloat, ENT_COMPAT, 'UTF-8'); ?>">
                    <?php echo JLayoutHelper::render('standardextension.content.intro_image', $this->item); ?>
                </div>
            <?php else: ?>
                <?php
                $class_item_text = "post d-flex col-12";
                $cItemText = "pt-2 pr-3 pb-2 pl-3";
                ?>
            <?php endif; ?>
            <div class="<?php echo $class_item_text; ?>">
                <div class="<?php echo $cItemText; ?>">
                    <?php if ($params->get('show_title')) : ?>
                        <h2 class="item-title" itemprop="headline">
                            <?php if ($params->get('link_titles') && $params->get('access-view')) : ?>
                                <a href="<?php echo JRoute::_(StandardextensionHelperRoute::getArticleRoute($this->item->slug, $this->item->catid, $this->item->language)); ?>" itemprop="url">
                                    <?php echo $this->escape($this->item->title); ?>
                                </a>
                            <?php else : ?>
                                <?php echo $this->escape($this->item->title); ?>
                            <?php endif; ?>
                        </h2>
                    <?php endif; ?>

                    <?php if ($this->item->state == 0) : ?>
                        <span class="label label-warning"><?php echo JText::_('JUNPUBLISHED'); ?></span>
                    <?php endif; ?>
                    <?php if ($isNotPublishedYet) : ?>
                        <span class="label label-warning"><?php echo JText::_('JNOTPUBLISHEDYET'); ?></span>
                    <?php endif; ?>
                    <?php if ($isExpired) : ?>
                        <span class="label label-warning"><?php echo JText::_('JEXPIRED'); ?></span>
                    <?php endif; ?>

                    <?php if ($canEdit || $params->get('show_print_icon') || $params->get('show_email_icon')) : ?>
                        <?php echo JLayoutHelper::render('standardextension.content.icons', array('params' => $params, 'item' => $this->item, 'print' => false)); ?>
                    <?php endif; ?>

                    <?php // Content is generated by content plugin event "onContentAfterTitle" ?>
                    <?php echo $this->item->event->afterDisplayTitle; ?>

                    <?php // Todo Not that elegant would be nice to group the params ?>
                    <?php $useDefList = ($params->get('show_modify_date') || $params->get('show_publish_date') || $params->get('show_create_date') || $params->get('show_hits') || $params->get('show_category') || $params->get('show_parent_category') || $params->get('show_author') || $assocParam);
                    ?>

                    <?php if ($useDefList && ($info == 0 || $info == 2)) : ?>
                        <?php // Todo: for Joomla4 joomla.content.info_block.block can be changed to joomla.content.info_block  ?>
                        <?php echo JLayoutHelper::render('standardextension.content.info_block.block', array('item' => $this->item, 'params' => $params, 'position' => 'above')); ?>
                    <?php endif; ?>
                    <?php if ($info == 0 && $params->get('show_tags', 1) && !empty($this->item->tags->itemTags)) : ?>
                        <?php echo JLayoutHelper::render('standardextension.content.tags', $this->item->tags->itemTags); ?>
                    <?php endif; ?>

                    <?php // echo JLayoutHelper::render('standardextension.content.intro_image', $this->item); ?>

                    <?php // Content is generated by content plugin event "onContentBeforeDisplay" ?>
                    <?php echo $this->item->event->beforeDisplayContent; ?>

                    <?php echo $this->item->introtext; ?>

                    <?php if ($info == 1 || $info == 2) : ?>
                        <?php if ($useDefList) : ?>
                            <?php // Todo: for Joomla4 joomla.content.info_block.block can be changed to joomla.content.info_block ?>
                            <?php echo JLayoutHelper::render('standardextension.content.info_block.block', array('item' => $this->item, 'params' => $params, 'position' => 'below')); ?>
                        <?php endif; ?>
                        <?php if ($params->get('show_tags', 1) && !empty($this->item->tags->itemTags)) : ?>
                            <?php echo JLayoutHelper::render('standardextension.content.tags', $this->item->tags->itemTags); ?>
                        <?php endif; ?>
                    <?php endif; ?>

                    <?php
                    if ($params->get('show_readmore') && $this->item->readmore) :
                        if ($params->get('access-view')) :
                            $link = JRoute::_(StandardextensionHelperRoute::getArticleRoute($this->item->slug, $this->item->catid, $this->item->language));
                        else :
                            $menu = JFactory::getApplication()->getMenu();
                            $active = $menu->getActive();
                            $itemId = $active->id;
                            $link = new JUri(JRoute::_('index.php?option=com_users&view=login&Itemid=' . $itemId, false));
                            $link->setVar('return', base64_encode(StandardextensionHelperRoute::getArticleRoute($this->item->slug, $this->item->catid, $this->item->language)));
                        endif;
                        ?>

                        <?php echo JLayoutHelper::render('standardextension.content.readmore', array('item' => $this->item, 'params' => $params, 'link' => $link)); ?>

                    <?php endif; ?>
                </div>
            </div>
        </div>
        <?php if ($isUnpublished) : ?>
        </div>
    <?php endif; ?>

    <?php // Content is generated by content plugin event "onContentAfterDisplay" ?>
    <?php echo $this->item->event->afterDisplayContent; ?>
</div>

